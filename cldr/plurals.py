#!/usr/bin/env python3
"""Writes Tsuji's plural rule table and its test samples from CLDR's plurals.xml.

The cardinal rules of CLDR's common/supplemental/plurals.xml become
shared/src/dev/taihei/tsuji/CldrPlurals.scala, and the samples CLDR gives for each rule
(@integer and @decimal) become shared/test/src/dev/taihei/tsuji/CldrPluralSamples.scala, against
which the tests check every rule set on the JVM and on Scala.js.

To move to another CLDR release, download that release's plurals.xml into a directory of its own
and run, from the repository root:

    python3 -I cldr/plurals.py <path to plurals.xml> <CLDR version, such as 49>

then `make fmt validate`, and update the CLDR version in README.md and NOTICE. The data is
Unicode, Inc.'s, under the Unicode License v3 (NOTICE).
"""

import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAIN = ROOT / "shared" / "src" / "dev" / "taihei" / "tsuji" / "CldrPlurals.scala"
TEST = ROOT / "shared" / "test" / "src" / "dev" / "taihei" / "tsuji" / "CldrPluralSamples.scala"

CATEGORIES = ["zero", "one", "two", "few", "many", "other"]
# What a condition may hold: the operands, the operators, numbers, ranges and lists.
CONDITION = re.compile(r"^[nivwftce0-9 .,%=!a-z]*$")
SAMPLES = re.compile(r"^[0-9.,~ c…]*$")


def split_rule(text):
    """The condition, the @integer samples and the @decimal samples of one rule."""
    condition, _, samples = text.partition("@")
    samples = "@" + samples if samples else ""
    integers = re.search(r"@integer([^@]*)", samples)
    decimals = re.search(r"@decimal([^@]*)", samples)
    return (
        " ".join(condition.split()),
        " ".join(integers.group(1).split()) if integers else "",
        " ".join(decimals.group(1).split()) if decimals else "",
    )


def checked(value, pattern, what):
    if not pattern.match(value) or '"' in value or "\\" in value:
        sys.exit(f"unexpected {what}: {value!r}")
    return value


def main():
    if len(sys.argv) != 3 or not re.fullmatch(r"[0-9]+(\.[0-9]+)?", sys.argv[2]):
        sys.exit("usage: python3 -I cldr/plurals.py <plurals.xml> <CLDR version>")
    tree = ET.parse(sys.argv[1])
    cardinal = [p for p in tree.getroot().iter("plurals") if p.get("type") == "cardinal"]
    if len(cardinal) != 1:
        sys.exit("plurals.xml has no single <plurals type=\"cardinal\">")
    version = sys.argv[2]

    rule_sets, samples = [], []
    seen = set()
    for rules in cardinal[0].iter("pluralRules"):
        locales = " ".join(rules.get("locales").split())
        for locale in locales.split():
            if locale in seen:
                sys.exit(f"{locale} has two rule sets")
            seen.add(locale)
        checked(locales, re.compile(r"^[A-Za-z_ ]+$"), "locales")
        conditions = []
        for rule in rules.iter("pluralRule"):
            category = rule.get("count")
            if category not in CATEGORIES:
                sys.exit(f"unknown category {category}")
            condition, integers, decimals = split_rule(rule.text or "")
            checked(condition, CONDITION, "condition")
            checked(integers, SAMPLES, "samples")
            checked(decimals, SAMPLES, "samples")
            if category == "other":
                if condition:
                    sys.exit(f"other has a condition in {locales}")
            else:
                conditions.append((category, condition))
            samples.append((locales, category, integers, decimals))
        rule_sets.append((locales, conditions))
    if "root" not in seen:
        sys.exit("plurals.xml has no rules for root")

    header = (
        f"// Generated by cldr/plurals.py from CLDR {version}, common/supplemental/plurals.xml.\n"
        "// Do not edit: run the script again (see its header). The data is Copyright Unicode, Inc.,\n"
        "// under the Unicode License v3 (SPDX-License-Identifier: Unicode-3.0), as NOTICE says.\n"
        "package dev.taihei.tsuji\n\n"
    )

    main_lines = [header,
                  "private[tsuji] object CldrPlurals:\n\n",
                  "  /** The CLDR release these cardinal plural rules come from. */\n",
                  f"  val Version: String = \"{version}\"\n\n",
                  "  // Per rule set: the locales it applies to, and its categories in CLDR's order, each with its\n",
                  "  // condition. `other` has none and is left out: it is whatever no condition holds for.\n",
                  "  val RuleSets: List[(String, List[(String, String)])] = List(\n"]
    for locales, conditions in rule_sets:
        rules = ", ".join(f"\"{c}\" -> \"{cond}\"" for c, cond in conditions)
        main_lines.append(f"    \"{locales}\" -> List({rules}),\n")
    main_lines.append("  )\n\nend CldrPlurals\n")

    test_lines = [header,
                  "object CldrPluralSamples:\n\n",
                  f"  val Version: String = \"{version}\"\n\n",
                  "  // Per rule: the locales of its rule set, its category, and CLDR's @integer and @decimal\n",
                  "  // samples, as plurals.xml writes them.\n",
                  "  val Samples: List[(String, String, String, String)] = List(\n"]
    for locales, category, integers, decimals in samples:
        test_lines.append(f"    (\"{locales}\", \"{category}\", \"{integers}\", \"{decimals}\"),\n")
    test_lines.append("  )\n\nend CldrPluralSamples\n")

    MAIN.write_text("".join(main_lines), encoding="utf-8")
    TEST.write_text("".join(test_lines), encoding="utf-8")
    print(f"CLDR {version}: {len(rule_sets)} rule sets, {len(seen)} locales, {len(samples)} rules")


if __name__ == "__main__":
    main()
