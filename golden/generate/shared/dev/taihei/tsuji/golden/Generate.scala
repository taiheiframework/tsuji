package dev.taihei.tsuji.golden

import scala.annotation.nowarn
import scala.util.control.NonFatal

import zio.json.*

import dev.taihei.tsuji.*

// Writes the golden files: what the released taihei-tsuji 5.0.1 writes for each value of the
// corpus, and what it reads from each input, as a Scala source on standard output. It runs
// against the 5.0.1 jars (build.mill, golden.jvm and golden.js), never against this repository's
// own code. An entry is "<what>|<case>" -> what 5.0.1 gave: the JSON it wrote, or for a read
// the value it read, written out again, or "refused".
@nowarn("cat=deprecation")
object Generate:

  given Catalogues = Corpus.catalogues

  private def withoutText(m: Message): String = Message.encoder(withText = false).encodeJson(m, None).toString

  private def written(name: String, w: Written): List[(String, String)] = w match
    case Written.Msg(m, withText) => List(s"write|$name" -> Message.encoder(withText).encodeJson(m, None).toString)
    case Written.Disp(d)          => List(s"write|$name" -> d.toJson)
    case Written.Txt(t)           => List(s"write|$name" -> t.toJson)
    case Written.Legacy(m)        => List(s"write|$name" -> m.toJson)
    case Written.Lang(l)          => List(s"write|$name" -> l.toJson, s"write key|$name" -> Map(l -> 1).toJson)
    case Written.Key(k)           =>
      val key = MessageKey.parse(k).toOption.get
      List(s"write|$name" -> key.toJson, s"write key|$name" -> Map(key -> 1).toJson)
    case Written.Cat(c)           => List(s"write|$name" -> c.toJson)

  private def displayable(d: Displayable): String = d match
    case m: Message        => "message " + withoutText(m)
    case t: Text           => "text " + t.toJson
    case l: legacy.Message => "legacy " + l.toJson
    case other             => "other " + other.toString

  // A read that throws is recorded too: 5.0.1 is the record, not the standard.
  private def result[A](read: => Either[String, A])(show: A => String): String =
    try read.fold(_ => "refused", show)
    catch case NonFatal(e) => s"threw ${e.getClass.getName}"

  def entries(extra: List[(String, String)]): List[(String, String)] =
    val writes = Corpus.writes.flatMap(written)
    val reads  = Corpus.reads.flatMap: (name, input) =>
      List(
        s"message|$name" -> result(input.fromJson[Message])(withoutText),
        s"displayable|$name" -> result(input.fromJson[Displayable])(displayable),
        s"text|$name" -> result(input.fromJson[Text])(_.toJson),
        s"legacy|$name" -> result(input.fromJson[legacy.Message])(_.toJson),
      )
    val values = Corpus.values.flatMap: (name, input) =>
      List(
        s"language|$name" -> result(input.fromJson[Language])(_.toJson),
        s"key|$name" -> result(input.fromJson[MessageKey])(_.toJson),
      )
    val keys   = Corpus.keys.flatMap: (name, input) =>
      List(
        s"language key|$name" -> result(input.fromJson[Map[Language, Int]])(_.toJson),
        s"key key|$name" -> result(input.fromJson[Map[MessageKey, Int]])(_.toJson),
      )
    val parsed = Corpus.catalogueInputs.map: (name, input) =>
      s"catalogue|$name" -> result(Catalogue.parse(input).left.map(_.toString)): c =>
        (c.toJson :: c.problems.map(_.toString)).mkString("\n")
    writes ++ reads ++ values ++ keys ++ parsed ++ extra

  end entries

  // A string as a Scala literal of printable ASCII: everything else as a \uXXXX escape, which
  // Scala 3 reads inside a string literal only, so the file stays exact for any char, an
  // unpaired surrogate included.
  private def literal(s: String): String =
    val hex = "0123456789abcdef"
    val out = new java.lang.StringBuilder("\"")
    s.foreach: c =>
      if c >= ' ' && c <= '~' && c != '"' && c != '\\' then out.append(c)
      else
        out.append("\\u")
        (12 to 0 by -4).foreach(shift => out.append(hex.charAt((c >> shift) & 0xf)))
    out.append('"').toString

  // A long string is split, and joined at run time: the JVM keeps a string constant in at most
  // 65535 bytes, and the compiler would fold a literal concatenation into one.
  private def value(s: String): String =
    if s.length <= 2000 then literal(s)
    else s.grouped(2000).map(literal).mkString("Seq(", ", ", ").mkString")

  def source(platform: String, entries: List[(String, String)]): String =
    val names = entries.map(_._1)
    require(names.distinct.size == names.size, s"duplicate names: ${names.diff(names.distinct)}")
    val parts = entries.grouped(100).toList
    val defs  = parts.zipWithIndex.map: (part, i) =>
      part
        .map((k, v) => s"      ${literal(k)} -> ${value(v)},")
        .mkString(s"  private def part$i: List[(String, String)] =\n    List(\n", "\n", "\n    )\n")
    s"""package dev.taihei.tsuji.golden
       |
       |// Generated by golden/generate from the released taihei-tsuji 5.0.1 on $platform (see
       |// build.mill, object golden). Do not edit: regenerate it.
       |object Golden501:
       |
       |  val platform = "$platform"
       |
       |  // ${entries.size} entries.
       |  lazy val entries: Map[String, String] =
       |    List(${parts.indices.map(i => s"part$i").mkString(", ")}).flatten.toMap
       |
       |${defs.mkString("\n")}
       |end Golden501
       |""".stripMargin

  end source

end Generate
